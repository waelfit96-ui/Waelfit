export const GRADE = (s) =>
  s >= 90 ? { label: 'Excellent', tone: 'good' } :
  s >= 75 ? { label: 'Good', tone: 'good' } :
  s >= 60 ? { label: 'Needs work', tone: 'warn' } :
            { label: 'High risk: correct first', tone: 'bad' };

